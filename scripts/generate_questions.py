#!/usr/bin/env python3
"""Generate the template questions and gold answers for a pinned store.

The Rhea set (generator 0.4.x, frozen as b204846e) is generated by scripts/generate_questions_rhea.py, with
the Rhea line's generator (harness/qgen_rhea). This script's rhea-142 path is the single-tier 0.2 generator,
kept only for the shared-machinery tests (generate() with no profile); run on rhea-142 it refuses.

Usage:
  uv run python scripts/generate_questions.py --graph uniprot-sp-2026_03 --endpoint http://localhost:7020/ \
      --seed 20261018 --per-template 43 --out data/questions/uniprot-sp-2026_03/ [--knobs knobs.json] \
      [--calibration-round 1 | --prior-round-questions round-1.jsonl]
  uv run python scripts/generate_questions.py --graph a15 --seed 20261018 --per-template 43 \
      --out ~/project/private/a15/questions/      (on run-node only; see below)
  uv run python scripts/generate_questions.py --graph text2sparql-ck26 --endpoint http://localhost:7021/ \
      --seed 20261019 --per-template 50 --out data/questions/text2sparql-ck26/

The store is checked first: its triples per named graph must equal the pinned
store's (stores/rhea-142/expected_counts.json for Rhea, the descriptor
stores/<graph>/store.json otherwise), so the questions are never generated
against the wrong store. ``--knobs`` overrides difficulty knobs of a two-tier
profile (JSON object). ``--calibration-round`` sets the structural-step knobs
of that round (UniProt: 1 reproduces the round-1 set, 2 is the default).

UniProt round 2 keeps its test questions off the anchors of round-1 dev
questions, so it needs the frozen round-1 file (sha256 b805acd9..., checked):
``git show ad85b72:data/questions/uniprot-sp-2026_03/questions.jsonl > round-1.jsonl``
or a ``--calibration-round 1`` run, passed as ``--prior-round-questions``.

a15 is private: the endpoint, credentials and graph IRI are read from mode-600
files (~/.config/www-2027/a15_*), the vocabulary from the private file named by
A15_VOCAB, and the output must go under ~/project/private/, written mode 600.
Its store is counted per predicate (no GRAPH ?g scan) before and after the run.

``--extension`` writes the bank-only extension (harness/qgen/extension.py):
more gold queries from the frozen set's templates and knobs, seeded from the
frozen file (sha256 checked against the pin), with no question texts, into
``--out``/questions-ext.jsonl and ``--out``/manifest.json (never the frozen
set's directory). The UniProt extension (N_test = 1,260):
  uv run python scripts/generate_questions.py --graph uniprot-sp-2026_03 --extension \
      --endpoint http://localhost:7020/ --seed 20271019 --per-template 214 \
      --prior-round-questions round-1.jsonl --out data/questions/uniprot-sp-2026_03/extension/
``--prior-dev-anchors drop`` drops the round-1 dev-anchor rule (then no
``--prior-round-questions``); it is kept by default (ruling in the design log, entry 52).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
import time
from pathlib import Path

from harness.qgen.generate import MAX_SECONDS, generate, store_triples, write_outputs
from harness.qgen.profiles import PROFILES, TEMPLATE_SETS, expected_counts, store_mismatches, with_knobs
from harness.sparql import SparqlClient, VirtuosoClient

REPO = Path(__file__).resolve().parent.parent
DEFAULT_EXPECTED = REPO / "stores" / "rhea-142" / "expected_counts.json"
CONFIG = Path("~/.config/www-2027").expanduser()
PRIVATE_ROOT = Path("~/project/private").expanduser()
# Client time-outs; the server's is twice each (harness.sparql.VirtuosoClient), at most 280 s. Golds
# must finish within the profile's gold_max_seconds (10 s) and pools within pool_max_seconds (60 s); the
# confirmation of each gold runs at the highest time-out the store allows (design ruling (a), design log).
A15_GOLD_TIMEOUT = 120.0
A15_POOL_TIMEOUT = 140.0
A15_CONFIRM_TIMEOUT = 140.0


def _a15_clients(endpoint: str | None) -> tuple[VirtuosoClient, VirtuosoClient, VirtuosoClient, str]:
    from harness.qgen import a15

    endpoint = endpoint or a15.VOCAB.endpoint
    # a configured row limit (private configuration): an answer reaching it is marked cut, never taken as whole
    files = (CONFIG / "a15_sparql_user", CONFIG / "a15_sparql_password", CONFIG / "a15_graphs.txt",
             CONFIG / "a15_result_cap")
    gold = VirtuosoClient.from_files(endpoint, *files, timeout_s=A15_GOLD_TIMEOUT)
    pool = VirtuosoClient.from_files(endpoint, *files, timeout_s=A15_POOL_TIMEOUT)
    confirm = VirtuosoClient.from_files(endpoint, *files, timeout_s=A15_CONFIRM_TIMEOUT)
    return gold, pool, confirm, endpoint


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--graph", default="rhea-142", choices=sorted(PROFILES))
    ap.add_argument("--knobs", type=Path, help="JSON object overriding difficulty knobs (two-tier profiles)")
    ap.add_argument("--calibration-round", type=int, help="the structural-step knobs of this calibration round")
    ap.add_argument("--prior-round-questions", type=Path,
                    help="questions file of the earlier calibration round whose dev anchors this round's test questions "
                         "avoid (required when the round pins one; its sha256 is checked)")
    ap.add_argument("--endpoint", help="SPARQL endpoint (required except for a15, whose vocabulary names it)")
    ap.add_argument("--seed", type=int, required=True)
    ap.add_argument("--per-template", type=int, default=None, help="default 40; with --extension 214 (N_test = 1,260)")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--templates", nargs="*", help="subset of template ids (default: all)")
    ap.add_argument("--min-preferred-share", type=float, default=1.0,
                    help="share of each template's questions that must have the variants' preferred properties "
                         "(discriminating direct vs transitive, or graph scope) when the pool allows; default all")
    ap.add_argument("--extension", action="store_true",
                    help="write the bank-only extension of the frozen set (no question texts; see above)")
    ap.add_argument("--frozen-questions", type=Path,
                    help="extension: the frozen questions file (default data/questions/<graph>/questions.jsonl)")
    ap.add_argument("--prior-dev-anchors", choices=["keep", "drop"], default="keep",
                    help="extension: keep or drop the earlier round's dev-anchor rule (default keep: ruling in the design log, entry 52)")
    ap.add_argument("--expected-counts", default=None,
                    help="JSON of expected triples per named graph (default: the pinned store's counts, see "
                         "above); an empty string skips the check")
    args = ap.parse_args(argv)

    private = args.graph == "a15"
    if private:
        os.umask(0o077)
        out = args.out.expanduser().resolve()
        if PRIVATE_ROOT.resolve() not in out.parents and out != PRIVATE_ROOT.resolve():
            print(f"a15 output must go under {PRIVATE_ROOT}", file=sys.stderr)
            return 2
    elif not args.endpoint:
        print("--endpoint is required", file=sys.stderr)
        return 2
    if args.extension:
        return extension_main(args)
    if args.graph == "rhea-142":
        print("the Rhea set is generated by scripts/generate_questions_rhea.py (the Rhea line's generator); "
              "this script's rhea-142 path is the 0.2 generator kept for the shared-machinery tests", file=sys.stderr)
        return 2
    if args.per_template is None:
        args.per_template = 40
    if args.per_template < 10:
        print("note: fewer than 10 questions per template is below the experiment's minimum", file=sys.stderr)
    profile = PROFILES[args.graph]
    if args.knobs:
        if profile is None:
            print("--knobs needs a two-tier profile", file=sys.stderr)
            return 2
        profile = with_knobs(profile, json.loads(args.knobs.read_text()))
    if args.calibration_round is not None:
        if profile is None or args.calibration_round not in profile.calibration_rounds:
            print(f"no calibration round {args.calibration_round} for {args.graph}", file=sys.stderr)
            return 2
        profile = with_knobs(profile, dict(profile.calibration_rounds[args.calibration_round]))
    by_id = {t.id: t for t in TEMPLATE_SETS[args.graph]}
    templates = [by_id[t] for t in args.templates] if args.templates else list(TEMPLATE_SETS[args.graph])
    expected = expected_counts(args.graph) if args.expected_counts is None else (
        json.loads(Path(args.expected_counts).read_text()) if args.expected_counts else None
    )
    if isinstance(expected, dict) and "graphs" in expected:
        expected = dict(expected["graphs"])
    confirm_client = None
    if private:
        gold_client, pool_client, confirm_client, args.endpoint = _a15_clients(args.endpoint)
    else:
        gold_client = SparqlClient(args.endpoint, timeout_s=MAX_SECONDS)
        # Shared stores allow client time-outs up to 290 s.
        pool_client = SparqlClient(args.endpoint, timeout_s=290)
    count = profile.store_count if profile is not None and profile.store_count else store_triples
    if profile is not None and profile.pinned_triples is not None and args.expected_counts is None:
        expected = dict(profile.pinned_triples)
    prior_records = None
    if args.prior_round_questions:
        lines = args.prior_round_questions.read_text(encoding="utf-8").splitlines()
        prior_records = [json.loads(line) for line in lines]
    pin = profile.prior_dev_round() if profile is not None else None
    if (pin is None) != (prior_records is None):
        if pin is None:
            print("--prior-round-questions given, but this round avoids no earlier round's dev anchors", file=sys.stderr)
        else:
            print(f"this round keeps its test questions off the round-{pin[0]} dev anchors: pass the round-{pin[0]} "
                  f"questions (sha256 {pin[1]}) with --prior-round-questions", file=sys.stderr)
        return 2

    if expected is not None:
        mismatches = store_mismatches(count(pool_client), expected)
        if mismatches:
            print("store mismatch, refusing to generate:\n  " + "\n  ".join(mismatches), file=sys.stderr)
            return 2
    else:
        print(f"note: no pinned triple counts for {args.graph}; the store is not checked", file=sys.stderr)

    gen = generate(
        gold_client, args.seed, args.per_template, templates, pool_client=pool_client,
        min_preferred_share=args.min_preferred_share, profile=profile, prior_records=prior_records,
        confirm_client=confirm_client,
    )
    manifest_args = dict(seed=args.seed, per_template=args.per_template, endpoint=args.endpoint, templates=templates)
    if profile is not None:
        manifest_args["profile"] = profile
    if confirm_client is not None:
        manifest_args["confirm_settings"] = confirm_client.settings()
    if expected is not None and private:
        mismatches = store_mismatches(count(pool_client), expected)
        if mismatches:
            print("store changed during the run, refusing to write:\n  " + "\n  ".join(mismatches), file=sys.stderr)
            return 2
    qpath, mpath = write_outputs(args.out, gen, **manifest_args)
    if private:
        for path in (qpath, mpath):
            os.chmod(path, 0o600)
    for t in templates:
        rows = [r for r in gen.records if r["template"] == t.id]
        dev = sum(r["split"] == "dev" for r in rows)
        tiers = ""
        if profile is not None and profile.two_tier:
            tiers = "  " + ", ".join(
                f"{tier} {sum(1 for r in rows if r['tier'] == tier)} "
                f"({sum(1 for r in rows if r['tier'] == tier and r['split'] == 'dev')} dev)"
                for tier in profile.tier_counts(args.per_template)
            )
        print(f"{t.id:20} {len(rows):3} questions ({dev} dev, {len(rows) - dev} test){tiers}")
        if len(rows) < args.per_template:
            print(f"  warning: only {len(rows)} of {args.per_template} requested", file=sys.stderr)
        for v, s in gen.stats[t.id].items():
            if s.quota is not None and s.accepted < s.quota:
                print(f"  warning: {t.id}/{v} filled {s.accepted} of its quota {s.quota} (pool short; others made up)",
                      file=sys.stderr)
    overlaps = gen.overlaps
    print(f"split overlap: {len(overlaps['nested'])} nested dev/test answer pairs (refused if any); "
          f"{len(overlaps['intersecting'])} dev/test pairs share some rows")
    by_template: dict[str, int] = {}
    for pair in overlaps["intersecting"]:
        by_template[pair["template"]] = by_template.get(pair["template"], 0) + 1
    for template, n in by_template.items():
        print(f"  {template:20} {n} intersecting pairs")
    sensitive = [r for r in gen.records if r["engine_sensitive"]]
    print(f"engine-sensitive questions: {len(sensitive)}")
    same = sorted({f"{r['template']}/{r['params']['variant']}" for r in gen.records if r["same_family_columns"]})
    print(f"variants with same-family answer columns (order stated): {', '.join(same) or 'none'}")
    for t in templates:
        rows = [r for r in gen.records if r["template"] == t.id]
        dvt = [r["discriminates_direct_vs_transitive"] for r in rows if r["discriminates_direct_vs_transitive"] is not None]
        scope = [r["discriminates_graph_scope"] for r in rows if r["discriminates_graph_scope"] is not None]
        print(f"  {t.id:20} direct-vs-transitive {sum(1 for x in dvt if x)}/{len(dvt)}  graph-scope {sum(1 for x in scope if x)}/{len(scope)}")
    if gen.prior is not None:
        print(f"round-{gen.prior['prior_round']} dev anchors: {len(gen.prior['redrawn'])} test questions redrawn "
              f"({', '.join(d['id'] for d in gen.prior['redrawn']) or 'none'}); "
              f"{len(gen.prior['other_variants']['questions'])} share an anchor with another variant's dev question")
    if gen.confirmation:
        counts = [e for t, vs in gen.confirmation.items() if t != "_confirmed_golds" for e in vs.values()]
        print(f"gold confirmation: {sum(e['confirmed'] for e in counts)} confirmed, "
              f"{sum(e['replaced'] for e in counts)} replaced (golds evaluated in sampling)")
    print(f"wrote {qpath} and {mpath}")
    return 0


def extension_main(args: argparse.Namespace) -> int:
    from harness.qgen.extension import (
        FROZEN_QUESTIONS_SHA256,
        PER_TEMPLATE,
        cluster_summary,
        generate_extension,
        write_extension,
    )

    if args.per_template is None:
        args.per_template = PER_TEMPLATE

    if args.knobs or args.calibration_round is not None or args.templates:
        print("--extension uses the frozen set's templates and knobs: no --knobs, --calibration-round or --templates",
              file=sys.stderr)
        return 2
    profile = PROFILES[args.graph]
    pin = FROZEN_QUESTIONS_SHA256.get(args.graph)
    if profile is None or pin is None:
        print(f"no frozen set pinned for an extension of {args.graph}", file=sys.stderr)
        return 2
    frozen_path = args.frozen_questions or REPO / "data" / "questions" / args.graph / "questions.jsonl"
    raw = frozen_path.read_bytes()
    if hashlib.sha256(raw).hexdigest() != pin:
        print(f"{frozen_path} is not the pinned frozen set (sha256 {pin})", file=sys.stderr)
        return 2
    if args.out.resolve() == frozen_path.resolve().parent:
        print(f"refusing to write the extension into the frozen set's directory {args.out}", file=sys.stderr)
        return 2
    keep = args.prior_dev_anchors == "keep"
    prior_records = None
    if args.prior_round_questions:
        if not keep:
            print("--prior-round-questions given, but --prior-dev-anchors drop", file=sys.stderr)
            return 2
        prior_records = [json.loads(line) for line in args.prior_round_questions.read_text(encoding="utf-8").splitlines()]
    if keep and profile.prior_dev_round() is not None and prior_records is None:
        rnd, sha = profile.prior_dev_round()
        print(f"--prior-dev-anchors keep needs the round-{rnd} questions (sha256 {sha}) as --prior-round-questions",
              file=sys.stderr)
        return 2
    gold_client = SparqlClient(args.endpoint, timeout_s=MAX_SECONDS)
    pool_client = SparqlClient(args.endpoint, timeout_s=290)  # shared stores allow client time-outs up to 290 s
    mismatches = store_mismatches(store_triples(pool_client), expected_counts(args.graph))
    if mismatches:
        print("store mismatch, refusing to generate:\n  " + "\n  ".join(mismatches), file=sys.stderr)
        return 2
    frozen = [json.loads(line) for line in raw.decode("utf-8").splitlines()]
    start = time.monotonic()
    ext = generate_extension(
        gold_client, frozen, seed=args.seed, per_template=args.per_template, profile=profile,
        templates=TEMPLATE_SETS[args.graph], pool_client=pool_client, prior_records=prior_records, prior_dev_anchors=keep,
    )
    qpath, mpath = write_extension(args.out, ext, endpoint=args.endpoint, frozen_path=frozen_path,
                                   wall_seconds=time.monotonic() - start)
    for t in ext.templates:
        rows = [r for r in ext.records if r["template"] == t.id]
        mix = ext.tier_mix[t.id]
        made_up = mix["made_up"]
        print(f"{t.id:20} {len(rows):3} new ({sum(r['split'] == 'dev' for r in rows)} dev, "
              f"{sum(r['split'] == 'test' for r in rows)} test); tiers {mix['drawn']}"
              + (f", {made_up['count']} {made_up['for_tier']} made up by {made_up['by_tier']}" if made_up else ""))
        for v in t.variants:
            vr = [r for r in rows if r["variant"] == v.name]
            s = ext.stats[t.id][v.name]
            print(f"  {v.name:34} {v.tier:13} {len(vr):3} of quota {s.quota:3} "
                  f"({sum(r['split'] == 'dev' for r in vr)} dev, {sum(r['split'] == 'test' for r in vr)} test)")
    shared = ext.checks["shared_entities"]["frozen_only"]
    print(f"frozen questions sharing an entity within a template (pre-existing, listed): {len(shared)}")
    print(f"clusters: frozen {cluster_summary(ext.frozen_clusters)}; bank {cluster_summary(ext.clusters)}")
    print(f"test-split clusters (map): frozen {ext.test_clusters['frozen']['map']}; bank {ext.test_clusters['bank']['map']}")
    if ext.prior is not None:
        print(f"round-{ext.prior['prior_round']} dev anchors: {len(ext.prior['redrawn'])} test questions redrawn")
    print(f"wrote {qpath} (sha256 {hashlib.sha256(qpath.read_bytes()).hexdigest()}) and {mpath}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
